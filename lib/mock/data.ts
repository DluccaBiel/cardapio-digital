function weekRange(offsetWeeks: number): { start: Date; end: Date; label: string } {
  const now = new Date()
  const day = now.getDay() || 7
  const monday = new Date(now.getFullYear(), now.getMonth(), now.getDate() - day + 1 + offsetWeeks * 7)
  const sunday = new Date(monday.getFullYear(), monday.getMonth(), monday.getDate() + 6)
  const fmt = (d: Date) => `${String(d.getDate()).padStart(2, '0')}/${String(d.getMonth() + 1).padStart(2, '0')}`
  return { start: monday, end: sunday, label: `Segunda ${fmt(monday)} a Domingo ${fmt(sunday)}` }
}

export function getPeriodLabels() {
  const current = weekRange(-1)
  const previous = weekRange(-2)
  return { current: current.label, previous: previous.label }
}

